/** ADR-297 Phase 3 — the paint properties a variant's condition tree carries, as CSS properties. */
const PAINT_CSS_PROPERTIES = {
  backgroundColor: "background",
  color: "color",
  borderColor: "border-color",
} as const;

/**
 * A `null` leaf — no catalog paint in that state: Canvas draws no fill · no border and leaves the
 * glyph color to the owner. (`revert-layer` would also roll back the rule's own base block in the same
 * layer — a selected ColorSwatch drew a currentColor border the Canvas does not draw.)
 */
const NO_CATALOG_VALUE = {
  backgroundColor: "transparent",
  color: "inherit",
  borderColor: "transparent",
} as const;

/** A tree without the branches under `drop` conditions (a toggle-indicator's container paints no selected box). */
function withoutConditions<T>(
  tree: ConditionalValue<T>,
  drop: ReadonlySet<string>,
): ConditionalValue<T> {
  if (!isConditionNode(tree)) return tree;
  const out: Record<string, unknown> = {};
  for (const [key, child] of Object.entries(tree as Record<string, unknown>))
    if (!drop.has(key))
      out[key] =
        key === "variant" ||
        key === "size" ||
        key === "fillStyle" ||
        key === "staticColor" ||
        key === "fieldButton"
          ? Object.fromEntries(
              Object.entries(child as Record<string, unknown>).map(
                ([value, branch]) => [
                  value,
                  withoutConditions(branch as ConditionalValue<T>, drop),
                ],
              ),
            )
          : withoutConditions(child as ConditionalValue<T>, drop);
  return out as ConditionalValue<T>;
}

/**
 * ADR-297 Phase 3 — a rule's variant paint as CSS: each variant's condition tree under its
 * `[data-variant]` value, compiled by `compileConditionTree` (every condition inside `:where()`, so
 * the blocks share the component class's specificity and the tree order is the cascade — the same
 * order the Canvas evaluator reads). `null` leaves are `NO_CATALOG_VALUE`. A variant
 * whose background alpha is 0 paints no background in any state (Canvas multiplies every state's
 * background by it). `undefined` = the rule has no variants.
 */
export function variantPaintCssFor(
  specName: string,
  /** Only these paint properties (a composition-owned box's text color — `generateCSS` `_variantColorCss`). */
  only?: ReadonlySet<keyof typeof PAINT_CSS_PROPERTIES>,
): string[] | undefined {
  const rule = getComponentRulesTable()[specName];
  if (!rule?.variants) return undefined;
  const structure = rule.structure as { archetype?: string } | undefined;
  const indicator = structure?.archetype === "toggle-indicator";
  const root = `.react-aria-${specName}`;
  const blocks: { selector: string; media?: string; line: string }[] = [];
  for (const property of Object.keys(PAINT_CSS_PROPERTIES) as Array<
    keyof typeof PAINT_CSS_PROPERTIES
  >) {
    // (A toggle-indicator's background · border are its indicator box's — the rule's `partStateStyles`.)
    if (
      indicator &&
      (property === "borderColor" || property === "backgroundColor")
    )
      continue;
    if (only && !only.has(property)) continue;
    const variant: Record<string, ConditionalValue<string | null>> = {};
    for (const [name, v] of Object.entries(rule.variants)) {
      let tree = v.paint[property] as
        ConditionalValue<string | null> | undefined;
      if (tree === undefined) continue;
      if (property === "backgroundColor" && v.alpha === 0) tree = "transparent";
      if (indicator)
        tree = withoutConditions(tree, new Set(["isSelected", "isEmphasized"]));
      variant[name] = tree;
    }
    if (Object.keys(variant).length === 0) continue;
    // (A composition-owned box's text color — `only` — is the default variant's tree on the element itself:
    //  such an element (a Tab) carries no `data-variant` (the rule's variant is not a prop of it), so its
    //  states compile without the variant condition and the other variants' after it.)
    const defaultName = rule.defaultVariant ?? "default";
    const trees: ConditionalValue<string | null>[] =
      only && variant[defaultName] !== undefined
        ? [
            variant[defaultName]!,
            ...(Object.keys(variant).length > 1
              ? [
                  {
                    variant: Object.fromEntries(
                      Object.entries(variant).filter(
                        ([name]) => name !== defaultName,
                      ),
                    ),
                  } as ConditionalValue<string | null>,
                ]
              : []),
          ]
        : [{ variant } as ConditionalValue<string | null>];
    for (const block of trees.flatMap((tree) =>
      compileConditionTree(tree, root, PAINT_CSS_PROPERTIES[property]),
    )) {
      const value =
        block.value === null
          ? NO_CATALOG_VALUE[property]
          : typeof block.value === "string" && block.value.startsWith("{")
            ? tokenToCSSVar(block.value as TokenRef)
            : String(block.value);
      blocks.push({
        selector: block.selector,
        ...(block.media ? { media: block.media } : {}),
        line: `${block.property}: ${value};`,
      });
    }
  }
  return [...groupedCss(blocks), ...variantImageCssFor(rule, root, only)];
}

/**
 * ADR-297 후속 ⑥ — the variants' gradient (`paint.backgroundImage`, S2 `Button.tsx` `gradient`) as
 * `background-image` over the background color. Its blocks come after the paint blocks: the color is the
 * `background` shorthand, which resets the image — at the same specificity (`:where()`) the later block wins.
 * The image covers the border box (`background-origin`), as the Canvas paints its rounded box.
 */
function variantImageCssFor(
  rule: ReturnType<typeof getComponentRulesTable>[string],
  root: string,
  only: ReadonlySet<string> | undefined,
): string[] {
  if (only) return [];
  const variant: Record<string, ConditionalValue<PaintImage | null>> = {};
  for (const [name, v] of Object.entries(rule.variants))
    if (v.paint.backgroundImage !== undefined)
      variant[name] = v.paint.backgroundImage;
  if (Object.keys(variant).length === 0) return [];
  const blocks: CssBlock[] = [];
  for (const block of compileConditionTree(
    { variant } as ConditionalValue<PaintImage | null>,
    root,
    "background-image",
  )) {
    const value =
      block.value === null
        ? "none"
        : paintGradientCss(block.value[0], (color) =>
            color.startsWith("{") ? tokenToCSSVar(color as TokenRef) : color,
          );
    blocks.push({
      selector: block.selector,
      ...(block.media ? { media: block.media } : {}),
      line: `background-image: ${value};`,
    });
    blocks.push({
      selector: block.selector,
      ...(block.media ? { media: block.media } : {}),
      line: "background-origin: border-box;",
    });
  }
  return groupedCss(blocks);
}

interface CssBlock {
  readonly selector: string;
  readonly media?: string;
  readonly line: string;
}

/**
 * Compiled blocks → sheet lines. Blocks are grouped by selector when that keeps every property's own
 * block order (the cascade only orders blocks that set the same property); otherwise each block stands
 * alone, in order.
 */
function groupedCss(blocks: readonly CssBlock[]): string[] {
  const groups = new Map<
    string,
    { selector: string; media?: string; lines: string[] }
  >();
  const order = new Map<string, number>();
  const lastIndex = new Map<string, number>();
  let grouped = true;
  for (const block of blocks) {
    const key = `${block.media ?? ""}|${block.selector}`;
    if (!order.has(key)) order.set(key, order.size);
    const property = block.line.slice(0, block.line.indexOf(":"));
    const at = order.get(key)!;
    if ((lastIndex.get(property) ?? -1) > at) grouped = false;
    lastIndex.set(property, at);
    const group = groups.get(key);
    if (group) group.lines.push(block.line);
    else
      groups.set(key, {
        selector: block.selector,
        ...(block.media ? { media: block.media } : {}),
        lines: [block.line],
      });
  }
  const runs = grouped
    ? [...groups.values()]
    : blocks.map((block) => ({
        selector: block.selector,
        ...(block.media ? { media: block.media } : {}),
        lines: [block.line],
      }));
  const lines: string[] = [];
  for (const group of runs) {
    const body = group.lines.map((line) => `  ${line}`);
    if (group.media)
      lines.push(
        `${group.media} {`,
        `${group.selector} {`,
        ...body,
        "}",
        "}",
        "",
      );
    else lines.push(`${group.selector} {`, ...body, "}", "");
  }
  return lines;
}

const kebab = (property: string) =>
  property.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** A state-style leaf as CSS declarations — `focusRing` is a ring token (outline + offset). */
function stateStyleDeclarations(
  property: string,
  value: string | number,
): string[] {
  if (property === "focusRing") {
    if (value === "none") return ["outline: none;"];
    const ring = resolveFocusRingToken(value as TokenRef);
    return [
      `outline: ${ring.outline};`,
      `outline-offset: ${ring.outlineOffset};`,
    ];
  }
  const css =
    typeof value === "string" && value.startsWith("{shadow.")
      ? `var(--shadow-${value.slice(8, -1)})`
      : // (a length ref — `{length.…}` — is resolved by the sheet's length pass, like a rootSelectors string)
        typeof value === "string" &&
          value.startsWith("{") &&
          !value.startsWith("{length.")
        ? tokenToCSSVar(value as TokenRef)
        : String(value);
  return [`${kebab(property)}: ${css};`];
}

/**
 * ADR-297 Phase 3b — a rule's root state styles (`structure.stateStyles`) as CSS: each property's
 * condition tree compiled by `compileConditionTree` (conditions inside `:where()` — every block has
 * the same specificity, the tree order is the cascade). `undefined` = the rule has no tree.
 */
export function stateStylesCssFor(specName: string): string[] | undefined {
  const table = getComponentRulesTable();
  // (a lowercase rule key — `body` — is emitted under its PascalCase spec name)
  const rule =
    table[specName] ?? table[specName[0].toLowerCase() + specName.slice(1)];
  const trees = (
    rule?.structure as { stateStyles?: ComponentRuleStateStyles } | undefined
  )?.stateStyles;
  const parts = rule?.partStateStyles;
  if (!trees && !parts) return undefined;
  // (The state layer sits on the size blocks — `.react-aria-X[data-size]`, 0-2-0 — and overrides their
  //  values (a quiet Input's corner, a field Button's radius): its blocks carry the class twice, so
  //  every one is 0-2-0 (the old `.react-aria-X[data-disabled]` height) and the tree order alone
  //  orders them. The conditions stay inside `:where()`.)
  const root = `.react-aria-${specName}.react-aria-${specName}`;
  const blocks: CssBlock[] = [];
  for (const [property, tree] of Object.entries(trees ?? {}))
    for (const block of compileConditionTree(tree, root, property))
      for (const line of stateStyleDeclarations(property, block.value))
        blocks.push({
          selector: block.selector,
          ...(block.media ? { media: block.media } : {}),
          line,
        });
  // (ADR-297 Phase 3g — the parts: the template's `%` takes the conditions, `&` the doubled root.
  //  Each part stands in its own run — a part's blocks never reorder another target's.)
  const lines: string[] = [];
  for (const [template, partTrees] of Object.entries(parts ?? {})) {
    const anchored = template.includes("%")
      ? template
      : template.replace("&", "&%");
    const partBlocks: CssBlock[] = [];
    for (const [property, tree] of Object.entries(partTrees))
      for (const block of compileConditionTree(tree, "\u0000", property)) {
        if (!block.selector.startsWith("\u0000"))
          throw new Error(`PART_STATE_DOM_ONLY:${specName}:${template}`);
        const selector = anchored
          .replace("%", block.selector.slice(1))
          .replaceAll("&", root);
        for (const line of stateStyleDeclarations(property, block.value))
          partBlocks.push({
            selector,
            ...(block.media ? { media: block.media } : {}),
            line,
          });
      }
    lines.push(...groupedCss(partBlocks));
  }
  // (the state blocks close the size section — no trailing blank line before the next section)
  lines.unshift(...groupedCss(blocks));
  while (lines.at(-1) === "") lines.pop();
  return lines;
}

/**
 * ADR-297 Phase 3g — a rule without `structure` (no generated sheet: its DOM visuals are a manual sheet, its
 * catalog values inline — `domBinding.runtime.ts` `noSheet`) still gets its `partStateStyles` as a sheet of
 * state blocks only.
 */
export function stateOnlySheets(): { name: string; css: string }[] {
  const out: { name: string; css: string }[] = [];
  for (const [key, rule] of Object.entries(getComponentRulesTable())) {
    if (rule.structure || !rule.partStateStyles) continue;
    const name = key[0].toUpperCase() + key.slice(1);
    const css = generateCSS(
      {
        name,
        skipCSSGeneration: true,
        variants: {},
        sizes: {},
        render: { shapes: () => [] },
      } as unknown as ComponentSpec<unknown>,
      undefined,
      stateStylesCssFor(name),
    );
    if (css !== null) out.push({ name, css });
  }
  return out;
}

/**
 * 모든 스펙에서 CSS 파일 생성. Node 전용 — 브라우저 번들(`CSSGenerator`)에 두지 않는다.
 */
async function generateAllCSS(
  specs: ComponentSpec<unknown>[],
  outputDir: string,
): Promise<void> {
  const statePath = path.join(outputDir, "CatalogStates.css");
  const stateCss = catalogStateStylesheet();
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(statePath, "utf8")) !== stateCss)
      throw new Error("CATALOG_CSS_STALE:CatalogStates");
  } else await fs.writeFile(statePath, stateCss, "utf8");
  for (const { name, css } of stateOnlySheets()) {
    const filePath = path.join(outputDir, `${name}.css`);
    if (process.argv.includes("--check")) {
      if ((await fs.readFile(filePath, "utf8")) !== css)
        throw new Error(`CATALOG_CSS_STALE:${name}`);
    } else await fs.writeFile(filePath, css, "utf-8");
  }
  for (const spec of specs) {
    const css = generateCSS(
      spec,
      variantPaintCssFor(spec.name),
      stateStylesCssFor(spec.name),
      variantPaintCssFor(spec.name, new Set(["color"])),
    );
    if (css === null) {
      console.log(`  ⏭ Skipped: ${spec.name} (skipCSSGeneration)`);
      continue;
    }
    const filePath = path.join(outputDir, `${spec.name}.css`);
    if (process.argv.includes("--check")) {
      if ((await fs.readFile(filePath, "utf8")) !== css)
        throw new Error(`CATALOG_CSS_STALE:${spec.name}`);
    } else await fs.writeFile(filePath, css, "utf-8");
    console.log(
      `${process.argv.includes("--check") ? "Verified" : "Generated"}: ${filePath}`,
    );
  }
}

// ─── TEXT_LEAF virtual spec 합성 ─────────────────────────────────────────────
//
// ADR-912 단계5 step4: TEXT_LEAF 5개(Text/Heading/Paragraph/Code/Kbd) spec 파일을 삭제하기 전에
// spec 없이도 동일한 CSS 가 재생성되도록 rule+메타상수에서 virtual ComponentSpec input 을 합성한다.
//
// - 메타상수: name / archetype / element(placeholder) / containerStyles
// - sizes / variants / defaultVariant / defaultSize: getComponentRulesTable() 에서 읽어 변환
// - generateCSS 본체 로직 불변 — 입력 모양만 ComponentSpec 과 동형
//
// ComponentRuleSize → SizeSpec 변환: ComponentRuleSize 는 모두 optional 이므로
// 누락 필드(paddingX/paddingY/height/fontSize/borderRadius)를 0/"" 기본값으로 채워
// `as unknown as SizeSpec` 동형 캐스팅(builder 의 ruleSizeToSizeSpec 과 동일 패턴).

/**
 * ComponentRuleSize → SizeSpec 변환 (TEXT_LEAF 용).
 * paddingX/paddingY/height/fontSize/borderRadius 필수 필드를 기본값으로 채워 캐스팅.
 */
function ruleSizeToSizeSpec(
  s: Record<string, unknown>,
  paddingX = 0,
  paddingY = 0,
): SizeSpec {
  return {
    height: (s.height as number) ?? 0,
    paddingX: (s.paddingX as number) ?? paddingX,
    paddingY: (s.paddingY as number) ?? paddingY,
    fontSize:
      (s.fontSize as SizeSpec["fontSize"]) ?? ("" as SizeSpec["fontSize"]),
    borderRadius:
      (s.borderRadius as SizeSpec["borderRadius"]) ??
      ("" as SizeSpec["borderRadius"]),
    ...(s.lineHeight !== undefined
      ? { lineHeight: s.lineHeight as SizeSpec["lineHeight"] }
      : {}),
    ...(s.borderWidth !== undefined
      ? { borderWidth: s.borderWidth as number }
      : {}),
    ...(s.gap !== undefined ? { gap: s.gap as number } : {}),
    // ADR-912 collection item leaf (2026-06-14): ListBoxItem 의 `min-height` (virtual/short 콘텐츠
    //   축소 하한, line-box 최소) 가 rule.sizes.minHeight 에서 emit 되도록 변환에 포함. 미정의 leaf 는 미emit.
    ...(s.minHeight !== undefined
      ? { minHeight: s.minHeight as SizeSpec["minHeight"] }
      : {}),
    // Spectrum 식별성 하한 (2026-08-20): Button 의 `min-width`(2.25×height) 가 rule.sizes.minWidth
    //   에서 emit 되도록 변환에 포함 (CSSGenerator size.minWidth → `min-width: {n}px`). 미정의 leaf 는 미emit.
    ...(s.width !== undefined ? { width: s.width as SizeSpec["width"] } : {}),
    ...(s.minWidth !== undefined ? { minWidth: s.minWidth as number } : {}),
    // Spectrum guideline 수치 (2026-08-21): ProgressBar 768 / Tooltip 160 의 `max-width` 가
    //   rule.sizes.maxWidth 에서 emit 되도록 변환에 포함 (CSSGenerator size.maxWidth → `max-width: {n}px`).
    ...(s.maxWidth !== undefined ? { maxWidth: s.maxWidth as number } : {}),
    // ADR-912 collection item leaf (2026-06-14): ListBoxItem label `font-weight: 600` (semibold)
    //   가 rule.sizes.fontWeight 에서 emit 되도록 변환에 포함. 미정의 leaf 는 미emit (CSSGenerator
    //   가 size.fontWeight 미존재 시 font-weight 줄 자체를 skip).
    ...(s.fontWeight !== undefined
      ? { fontWeight: s.fontWeight as number }
      : {}),
    // ADR-912 box+text leaf 군 (2026-06-11): Button/ToggleButton/Icon 의 --icon-size/--icon-gap
    //   CSS 변수가 rule.sizes.iconSize/iconGap 에서 emit 되도록 변환에 포함. 미정의 leaf 는 미emit.
    ...(s.iconSize !== undefined ? { iconSize: s.iconSize as number } : {}),
    ...(s.iconGap !== undefined ? { iconGap: s.iconGap as number } : {}),
    // ADR-912 단계5 step4 (2026-06-17): Slider 의 column-gap (Label↔SliderOutput 가로 간격) 이
    //   rule.sizes.columnGap 에서 emit 되도록 변환에 포함 (CSSGenerator 가 size.columnGap 소비).
    //   sm/md 16 · lg/xl 20. gap(row 축)은 기존 처리. 미정의 leaf 는 미emit.
    ...(s.columnGap !== undefined
      ? { columnGap: s.columnGap as SizeSpec["columnGap"] }
      : {}),
    // ADR-912 단계5 step4 (2026-06-17): Slider 의 size별 track/thumb metric 이 nested indicator 에서
    //   emit 되도록 변환에 포함. generateSliderSizeMetrics 가 size.indicator.{trackHeight,thumbSize} 를
    //   nested 로 읽어 `.slider-track-bg/.slider-fill { height }` + `.react-aria-SliderThumb { width/height }`
    //   를 emit. ComponentRuleSize 의 nested indicator 를 SizeSpec.indicator(IndicatorSpec)로 그대로 전달.
    //   flat thumbSize(SliderTrack escape 전용)와 별개. 미정의 leaf 는 미emit.
    ...(s.indicator !== undefined
      ? { indicator: s.indicator as SizeSpec["indicator"] }
      : {}),
    // ADR-295 Phase 3c-3: the block's relative lengths (`ofHeight` · `em`) — the copy above holds their
    //   desktop px, the generator writes the formula.
    ...(ruleSizeLengthRefs(s) ? { lengthRefs: ruleSizeLengthRefs(s) } : {}),
  } as SizeSpec;
}

/**
 * A variant's rest paint — the `default` leaves of its condition trees (ADR-297 Phase 3i). The generated base block
 * paints the default variant with it (no `data-variant` match needed); every state is `variantPaintCssFor`.
 */
function variantRestPaint(v: ComponentRuleVariant): VariantRestPaint {
  const border = paintAt(v.paint.borderColor);
  return {
    background: paintAt(v.paint.backgroundColor) as TokenRef | undefined,
    text: (paintAt(v.paint.color) ?? "{color.neutral}") as TokenRef,
    ...(border !== undefined ? { border: border as TokenRef } : {}),
  };
}

/**
 * structure 보유 rule entry 를 rule(getComponentRulesTable) + 구조 메타 기반으로 virtual
 * ComponentSpec 배열로 합성. spec 파일 존재 여부와 무관 — virtual emit 집합은 `rule.structure`
 * 보유 여부가 정한다 (ADR-912 Phase 2 — generator-local STRUCTURE_META Map 삭제).
 */
/**
 * `rule.densities` → `composition.containerVariants.density` 합성 (2026-08-21).
 *
 * density 는 Spectrum 규칙상 폰트를 건드리지 않고 간격/수직 padding 만 바꾸므로 size 축과
 * 분리된 `densities` 에 산다. CSS 는 이미 containerVariants 를 `[data-{attr}="{value}"]` 로
 * emit 하므로, 별도 emit 경로를 만들지 않고 여기서 합성해 재사용한다.
 * 기존 containerVariants 가 있으면 보존하고 `density` 키만 얹는다.
 *
 * **수동 `containerVariants.density` 와 병합한다 (2026-08-21)**: 간격(gap/paddingY)만으로
 * 표현되지 않는 density 차이가 있다 — ToggleButtonGroup 의 compact 는 Spectrum 규칙상
 * 버튼이 **연결**되므로(양끝만 radius + `-1px` 겹침) nested selector 가 필요하다. 그건
 * `densities` 스키마로 표현할 수 없어 catalog 에 직접 쓰는데, 여기서 통째로 덮어쓰면
 * 그 nested 가 사라진다. 그래서 density 이름별로 `styles` 만 얹고 `nested` 는 보존한다.
 */
function mergeDensityVariants(
  composition: ComponentSpec<unknown>["composition"] | undefined,
  densities:
    | Record<string, { gap?: number; paddingY?: number; minHeight?: number }>
    | undefined,
): ComponentSpec<unknown>["composition"] {
  if (!densities || Object.keys(densities).length === 0) {
    return composition as ComponentSpec<unknown>["composition"];
  }

  const existing = (composition?.containerVariants?.density ?? {}) as Record<
    string,
    { styles?: Record<string, string>; nested?: unknown }
  >;
  const densityVariants: Record<string, unknown> = { ...existing };

  for (const [densityName, spacing] of Object.entries(densities)) {
    const styles: Record<string, string> = {};
    if (spacing.gap !== undefined) styles.gap = `${spacing.gap}px`;
    if (spacing.paddingY !== undefined) {
      styles["padding-top"] = `${spacing.paddingY}px`;
      styles["padding-bottom"] = `${spacing.paddingY}px`;
    }
    // (ADR-295 후속: an S2 cell minimum — `scaled(n)` — is its device formula.)
    if (spacing.minHeight !== undefined) {
      const ref = ruleSizeLengthRef(spacing, "minHeight");
      styles["min-height"] =
        (ref && ruleLengthCss(ref)) ?? `${spacing.minHeight}px`;
    }
    if (Object.keys(styles).length === 0) continue;
    // 수동 정의(주로 `nested`)를 보존하고 `styles` 만 얹는다 — 같은 속성이면 densities 우선
    //   (`densities` 가 간격의 SSOT 이고 수동 쪽은 표현 불가한 규칙만 담는다).
    const prev = existing[densityName];
    densityVariants[densityName] = {
      ...prev,
      styles: { ...prev?.styles, ...styles },
    };
  }

  if (Object.keys(densityVariants).length === 0) {
    return composition as ComponentSpec<unknown>["composition"];
  }

  return {
    ...(composition ?? {}),
    containerVariants: {
      ...(composition?.containerVariants ?? {}),
      density: densityVariants,
    },
  } as ComponentSpec<unknown>["composition"];
}

export function buildVirtualSpecs(): ComponentSpec<unknown>[] {
  const table = getComponentRulesTable();
  const result: ComponentSpec<unknown>[] = [];

  // ADR-912 Phase 2 (2026-06-19): STRUCTURE_META Map 삭제 → rule table 순회 기반 전환.
  //   virtual CSS emit 멤버십은 이제 `rule.structure` 보유 여부가 결정한다(generator-local
  //   structure SSOT 제거 — breakdown §2-3). `meta = rule.structure` 로 두면 기존 합성 로직
  //   (meta.archetype/element/states/composition/...)이 그대로 작동 → generated CSS byte-diff 0.
  for (const [key, rule] of Object.entries(table)) {
    const meta = rule.structure;
    if (!meta) continue;

    // D1(RAC)이 컨테이너 클래스의 권위다 (2026-08-21). binding 의 `source.component` 가 rule key 와
    //   다르면 DOM 에는 RAC 가 자기 이름으로 `.react-aria-{source.component}` 를 붙이므로,
    //   `.react-aria-{key}` 를 노리는 생성 CSS 는 **구조적으로 영원히 미매칭**이다. 시각은
    //   `source.component` 쪽 생성 CSS 가 담당하고, rule 의 값은 Skia 가 소비한다.
    //   실측 사례: TextArea (rac.primitive = TextField — RAC 에 TextArea **컨테이너** primitive 가
    //   없어 TextField 로 감싼다) → DOM 은 `.react-aria-TextField`, 생성 `TextArea.css` 는 전량 dead.
    //   더 나쁜 점은 `.react-aria-TextArea` 가 RAC 에서 **안쪽 `<textarea>`** 의 클래스라는 것 —
    //   그 이름으로 컨테이너 규칙(display:flex/gap)을 emit 하면 나중에 진짜 textarea 가 들어오는
    //   순간 엉뚱한 요소에 걸린다. 그래서 "안 걸리는 CSS 를 고치는" 방향이 아니라 만들지 않는다.
    //   컴포넌트 이름 목록이 아니라 binding 에서 파생 — 향후 같은 형태가 생겨도 자동 적용.
    const domComponent = getPrimitiveBinding(key)?.source;
    if (
      domComponent?.kind === "rac" &&
      domComponent.component !== key &&
      // lowercase key(body)는 아래에서 PascalCase 로 복원하므로 대소문자만 다른 경우는 제외.
      domComponent.component.toLowerCase() !== key.toLowerCase()
    ) {
      console.log(
        `  ⏭  Skipped CSS emit: ${key} (DOM class = .react-aria-${domComponent.component} — selector unmatchable)`,
      );
      continue;
    }

    // spec name: rule key 는 대부분 PascalCase(spec name 동일)이나, 일부 container shell(body)은
    //   canonical element.type 정합 위해 lowercase key 로 등재(componentRulesTable.body).
    //   CSS 파일명/selector 는 PascalCase 여야 하므로 lowercase key 는 capitalize 복원
    //   (현재 lowercase 이면서 structure 보유 = body 하나뿐 → "Body").
    const name =
      key[0] === key[0].toLowerCase()
        ? key[0].toUpperCase() + key.slice(1)
        : key;

    // sizes: rule.sizes 의 각 entry 를 SizeSpec 으로 변환
    const sizes: Record<string, SizeSpec> = {};
    for (const [sizeName, ruleSize] of Object.entries(rule.sizes)) {
      sizes[sizeName] = ruleSizeToSizeSpec(ruleSize as Record<string, unknown>);
    }

    // variants: 각 variant 의 휴지 칠 (조건 트리의 default)
    const variants: Record<string, VariantRestPaint> = {};
    for (const [variantName, ruleVariant] of Object.entries(rule.variants))
      variants[variantName] = variantRestPaint(ruleVariant);

    const virtualSpec: ComponentSpec<unknown> = {
      name,
      archetype: toArchetypeId(meta.archetype),
      element: meta.element as ComponentSpec<unknown>["element"],
      containerStyles:
        meta.containerStyles as ComponentSpec<unknown>["containerStyles"],
      defaultVariant: rule.defaultVariant,
      defaultSize: rule.defaultSize ?? "M",
      variants,
      sizes,
      ...(meta.defaultBorder === "color"
        ? { defaultBorderColorOnly: true }
        : {}),
      // skipCSSGeneration: DOM 시각을 수동 CSS 가 소유 (Label) — structure 는 Canvas 정본으로만.
      ...(meta.skipCSSGeneration ? { skipCSSGeneration: true } : {}),
      // skipStateStyles (ADR-258): 상태 시각은 rootSelectors 정본 — 기본 ring · opacity 블록 없음.
      ...(meta.skipStateStyles ? { skipStateStyles: true } : {}),
      // classAliases (ADR-253): 이 rule 의 sheet 가 같이 그리는 RAC class (Input → `<textarea>`).
      ...(meta.classAliases ? { classAliases: meta.classAliases } : {}),
      // fillStyleValues: the `fillStyle` values that pick the outline · subtle fills (InlineAlert's S2 names).
      ...(rule.fillStyleValues
        ? { fillStyleValues: rule.fillStyleValues }
        : {}),
      // ADR-259 Phase 3: a field's label row stands in its Label's place (S2 FieldLabel).
      ...(CATALOG_CONTEXTUAL_HELP_FIELDS.has(name)
        ? { partAliases: CATALOG_FIELD_LABEL_PART_ALIASES }
        : {}),
      // composition: rule 에 없는 CSS selector 메타(Link underline 등). 미설정 시 미적용.
      //   density (2026-08-21): `rule.densities` 를 `containerVariants.density` 로 합성해
      //   기존 emit 경로를 재사용한다 (`[data-density="compact"] { gap: 0px }`). Skia 는 같은
      //   `rule.densities` 를 `resolveCatalogDensityField` 로 읽으므로 두 consumer 가 동일
      //   SSOT 를 본다. densities 미정의 컴포넌트는 합성 자체가 없어 CSS diff 0.
      ...(meta.composition || rule.densities
        ? {
            composition: mergeDensityVariants(
              meta.composition as ComponentSpec<unknown>["composition"],
              rule.densities,
            ),
          }
        : {}),
      // indicatorMode: ToggleButtonGroup 의 selection indicator 구조. 미설정 시 미emit.
      ...(meta.indicatorMode
        ? {
            indicatorMode:
              meta.indicatorMode as unknown as ComponentSpec<unknown>["indicatorMode"],
          }
        : {}),
      // chart (ADR-194): 시리즈 팔레트·축 색을 CSS custom property 로 내보낸다.
      //   variants/sizes 두 축에 안 들어가는 **순서 있는 색 목록** 이라 rule top-level
      //   채널을 그대로 실어 보낸다. 미보유 rule 은 emit 0 (CSS diff 0).
      ...(rule.chart ? { chart: rule.chart } : {}),
      render: {
        shapes: () => [],
      },
    };

    result.push(virtualSpec);
    console.log(`  ✓ Synthesized virtual spec: ${name} (from rule table)`);
  }

  return result;
}

async function main(): Promise<void> {
  console.log("🔄 Starting CSS generation...\n");

  try {
    // 출력 디렉토리 생성
    await fs.mkdir(OUTPUT_DIR, { recursive: true });

    const specs = buildVirtualSpecs();

    if (specs.length === 0) {
      console.log("\n⚠️  No valid specs found");
      return;
    }

    // ADR-059 v2 Pre-Phase 0-D: delegation prefix SSOT 검증
    const violations = validateDelegationPrefixes(specs);
    if (violations.length > 0) {
      console.error("\n" + formatViolations(violations));
      process.exit(1);
    }
    console.log(`\n✓ Delegation prefix 검증 통과 (${specs.length} specs)`);

    // CSS 생성
    console.log("\n📝 Generating CSS files...\n");
    await generateAllCSS(specs, OUTPUT_DIR);
    await writeOrCheck(
      THEME_SEED_PATH,
      await format(themeSeedCss(), { parser: "css" }),
      "theme-seed",
    );

    console.log(
      `\n✅ Processed ${specs.length} catalog CSS inputs in ${OUTPUT_DIR}`,
    );
  } catch (error) {
    console.error("❌ CSS generation failed:", error);
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename)
  void main();
