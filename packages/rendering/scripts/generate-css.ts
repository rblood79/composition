/**
 * ADR-295 Decision 8 · 9 (R8) — Preview · Publish 기본 시트의 `--catalog-token-*` (기본 테마 resolver 값, desktop ·
 * 터치 두 벌). 테마 변수 (`#runtime-theme-vars`, layer 없음) 가 실리기 전 첫 프레임이 빌더 chrome 값이 아니라
 * 사용자 컴포넌트 값으로 그려지게 한다. 빌더 root 는 싣지 않는다 (`builder-catalog-vars.css` 가 소유).
 */
export function themeSeedCss(): string {
  const snapshot = resolveThemeSnapshot(
    createThemeDefinition("theme-seed", "Theme seed"),
    { baseTypographySeed: DEFAULT_BASE_TYPOGRAPHY },
  );
  const lines = (touch: boolean) =>
    (touch ? snapshot.touchCssVars : snapshot.cssVars.filter((v) => !v.isDark))
      .filter((v) => v.name.startsWith(CATALOG_TOKEN_VAR_PREFIX))
      .map((v) => `  ${v.name}: ${v.value};`)
      .join("\n");
  const pickerVars = (dark: boolean) =>
    Object.entries(dark ? darkColors : lightColors)
      .filter(([key]) => key.startsWith("picker-"))
      .map(
        ([key, value]) =>
          `  ${tokenToCSSVar(`{color.${key}}` as TokenRef).slice(4, -1)}: ${value};`,
      )
      .join("\n");
  return [
    "/* AUTO-GENERATED by packages/rendering/scripts/generate-css.ts — DO NOT EDIT MANUALLY",
    " * ADR-295: 기본 테마의 사용자 컴포넌트 치수 토큰 (resolveThemeSnapshot). Preview · Publish 전용 —",
    " * 테마 변수가 실리면 그 값이 이긴다. 빌더 root 는 builder-catalog-vars.css. */",
    "",
    "@layer preview-system {",
    `:root {\n${lines(false)}\n${pickerVars(false)}\n}`,
    `[data-theme="dark"] {\n${pickerVars(true)}\n}`,
    catalogTouchVarsCss(lines(true)).trimEnd(),
    "}",
    "",
  ].join("\n");
}

async function writeOrCheck(filePath: string, css: string, label: string) {
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(filePath, "utf8")) !== css)
      throw new Error(`CATALOG_CSS_STALE:${label}`);
  } else await fs.writeFile(filePath, css, "utf8");
}

