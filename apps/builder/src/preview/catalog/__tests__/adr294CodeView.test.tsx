/**
 * ADR-294 Phase 3 (G3) — an instance's component properties in the page code: a received event is
 * the instance's callback prop (`onSelect={…}` = `property:<key>`), a variable property its
 * attribute by name (`role={roleFilter}` — a reference, or a literal). Each reads back to the
 * document; unchanged code plans nothing; a name a RAC callback already has is refused.
 */
afterEach(() => vi.restoreAllMocks());

const HOME = "project:page:home" as EntryId<"page">;
const BODY = "project:node:home-body" as NodeId;
const GENERATED = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../../../../../packages/shared/src/codeView/__fixtures__/generated",
);

function golden(name: string, code: string) {
  const file = join(GENERATED, `${name}.tsx.txt`);
  const text = `// ADR-294 G3 — ${name}: a user component instance's event (onSelect) and variable property (role), generated by packages/shared/src/codeView/generate.ts.\n// Golden output of apps/builder/src/preview/catalog/__tests__/adr294CodeView.test.tsx (UPDATE_CODE_VIEW=1 rewrites).\n\n${code}`;
  if (process.env.UPDATE_CODE_VIEW === "1" || !existsSync(file)) {
    mkdirSync(GENERATED, { recursive: true });
    writeFileSync(file, text);
  }
  expect(text).toBe(readFileSync(file, "utf8"));
}

/** "UserPicker" (origin = a ListBox, event `select`, variable `role`) placed once (J). */
async function open() {
  vi.spyOn(console, "warn").mockImplementation(() => {});
  const h = await openAdr280Preview(["ListBox"]);
  const graph = () => h.workspace.runtime.graph;
  const run = (command: Parameters<typeof h.workspace.execute>[0]) =>
    act(() => {
      h.workspace.execute(command);
    });
  run(
    createComponent({
      id: h.ids[0] as NodeId,
      name: "UserPicker",
      newId: h.workspace.newId,
    }),
  );
  const project = graph().getEntry(graph().projectId);
  const definitionId = (
    project?.kind === "project" ? project.definitionIds.at(-1) : ""
  ) as EntryId<"definition">;
  const J = (graph().getEntry(BODY) as NodeEntry).children[0]! as NodeId;
  run(
    addComponentOutputProperty({
      definitionId,
      key: "propselect",
      name: "select",
      kind: "event",
    }),
  );
  run(
    addComponentOutputProperty({
      definitionId,
      key: "proprole",
      name: "role",
      kind: "variable",
      variable: {
        id: "project:stateVariable:role" as EntryId<"stateVariable">,
        valueType: "string",
        defaultValue: "guest",
      },
    }),
  );
  const variable = (name: string, defaultValue: string) => {
    const entry: StateVariableEntry = {
      kind: "stateVariable",
      id: `project:stateVariable:${name}` as EntryId<"stateVariable">,
      ownerId: HOME,
      name,
      valueType: "string",
      defaultValue,
    };
    run(addRecord({ entry }));
    return entry.id;
  };
  const roleFilter = variable("roleFilter", "admin");
  const picked = variable("picked", "");
  const data = { collections: [], endpoints: [] };
  const code = () => catalogCodeView(graph(), HOME, data)!.code;
  const apply = (edited: string) => {
    const session = catalogCodeViewSession(graph(), HOME, data)!;
    const before = session.baseline.code;
    return catalogCodeViewApply(
      h.workspace,
      session,
      edited,
      [{ fromA: 0, toA: before.length, insert: edited }],
      data,
    );
  };
  const rulesOf = (ownerId: string) => {
    const project = graph().getEntry(graph().projectId);
    return project?.kind === "project"
      ? project.interactionIds
          .map((id) => graph().getEntry(id) as InteractionEntry)
          .filter((rule) => rule.ownerId === ownerId)
      : [];
  };
  return {
    ...h,
    graph,
    run,
    definitionId,
    J,
    roleFilter,
    picked,
    code,
    apply,
    rulesOf,
  };
}

describe("ADR-294 G3 — the instance's event and variable property in the page code", () => {
  it("golden `picker`: role={roleFilter} · onSelect={setPicked} — read back with no problem, unchanged code plans nothing", async () => {
    const h = await open();
    h.run(
      setFields({
        targets: [{ kind: "node", id: h.J }],
        props: { proprole: { kind: "set", value: `!var.${h.roleFilter}` } },
      }),
    );
    h.run(
      addRecord({
        entry: {
          kind: "interaction",
          id: "project:interaction:pick" as EntryId<"interaction">,
          ownerId: h.J,
          trigger: "property:propselect",
          actions: [
            {
              opcode: "setState",
              variableId: h.picked,
              op: "set",
              value: "!event.value",
            },
          ],
        } as InteractionEntry,
      }),
    );
    const code = h.code();
    expect(code).toContain("role={roleFilter}");
    expect(code).toContain("onSelect={setPicked}");
    golden("picker", code);
    expect(parseCodeView(code).problems).toEqual([]);
    const revision = h.graph().revision;
    const same = h.apply(code);
    expect(same.rejected).toEqual([]);
    expect(h.graph().revision).toBe(revision);
    h.view.unmount();
  });

  it("writing onSelect makes the property:<key> rule; a two-Do handler reads back; removing it deletes the rule", async () => {
    const h = await open();
    const code = h.code();
    const tag = /<ListBox\b/;
    expect(code).toMatch(tag);
    const first = h.apply(code.replace(tag, "<ListBox onSelect={setPicked}"));
    expect(first.rejected).toEqual([]);
    expect(h.rulesOf(h.J).map((rule) => rule.trigger)).toEqual([
      "property:propselect",
    ]);
    expect(h.rulesOf(h.J)[0]!.actions).toEqual([
      {
        opcode: "setState",
        variableId: h.picked,
        op: "set",
        value: "!event.value",
      },
    ]);
    // (The regenerated two-Do form — what the code view writes — reads back the same.)
    h.run(
      addRecord({
        entry: {
          kind: "interaction",
          id: "project:interaction:two" as EntryId<"interaction">,
          ownerId: h.J,
          trigger: "property:propselect",
          actions: [{ opcode: "toast", message: "picked" }],
        } as InteractionEntry,
      }),
    );
    const two = h.code();
    expect(two).toContain("onSelect={(value) => {");
    expect(h.apply(two).rejected).toEqual([]);
    const removed = h.apply(
      two.replace(/ onSelect=\{\(value\) => \{[\s\S]*?\n\s*\}\}/, ""),
    );
    expect(removed.rejected).toEqual([]);
    expect(h.rulesOf(h.J)).toEqual([]);
    h.view.unmount();
  });

  it("a variable property: a literal ↔ a reference by its name; another type's variable is refused", async () => {
    const h = await open();
    const code = h.code();
    const literal = h.apply(
      code.replace(/<ListBox\b/, '<ListBox role="admin"'),
    );
    expect(literal.rejected).toEqual([]);
    expect((h.graph().getEntry(h.J) as NodeEntry).props.proprole).toEqual({
      kind: "set",
      value: "admin",
    });
    const reference = h.apply(
      h.code().replace('role="admin"', "role={roleFilter}"),
    );
    expect(reference.rejected).toEqual([]);
    expect((h.graph().getEntry(h.J) as NodeEntry).props.proprole).toEqual({
      kind: "set",
      value: `!var.${h.roleFilter}`,
    });
    // (A number variable is not a text property's value — the document refuses, nothing changes.)
    h.run(
      addRecord({
        entry: {
          kind: "stateVariable",
          id: "project:stateVariable:count" as EntryId<"stateVariable">,
          ownerId: HOME,
          name: "count",
          valueType: "number",
          defaultValue: 0,
        } as StateVariableEntry,
      }),
    );
    const refused = h.apply(
      h.code().replace("role={roleFilter}", "role={count}"),
    );
    expect(refused.rejected.length).toBeGreaterThan(0);
    expect((h.graph().getEntry(h.J) as NodeEntry).props.proprole).toEqual({
      kind: "set",
      value: `!var.${h.roleFilter}`,
    });
    h.view.unmount();
  });

  it("an event named like the root's RAC callback is refused (onAction would read back as RAC's)", async () => {
    const h = await open();
    let code: string | undefined;
    try {
      h.workspace.execute(
        renameComponentProperty({
          definitionId: h.definitionId,
          key: "propselect",
          name: "action",
        }),
      );
    } catch (error) {
      code = (error as { code?: string }).code;
    }
    expect(code).toBe("PROPERTY_NAME_TAKEN");
    h.view.unmount();
  });
});
