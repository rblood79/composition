/**
 * ADR-291 Phase 2 (Decision 9) — the code view's computed columns: `let <rows>Fields = {<key>:
 * {type, formula}}` (the formula over field keys, `type` the result type — one formula under two
 * types stays two columns, an array sub-property formula keeps `items[*].price`) and the rows
 * mapped through json-formula; golden 6 (`orders`). The block is an edit unit: a formula typed
 * over is stored over ids (one step, one Undo), unchanged code plans nothing (strict), a `type`
 * typed over is outside the vocabulary, and a rename of a read column changes the code, not the
 * stored formula (G1 in the code view).
 */
beforeAll(() => loadFormulaEngine());
afterEach(() => vi.restoreAllMocks());

const HOME = "project:page:home" as EntryId<"page">;
const BODY = "project:node:home-body" as NodeId;
const GENERATED = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../../../../../packages/shared/src/codeView/__fixtures__/generated",
);

/** The golden file (the ADR-284 set's helper): rewritten with `UPDATE_CODE_VIEW=1`. */
function golden(name: string, code: string) {
  const file = join(GENERATED, `${name}.tsx.txt`);
  const text = `// ADR-291 §Decision 9 — ${name} rebuilt in the builder, generated by packages/shared/src/codeView/generate.ts.\n// Golden output of apps/builder/src/preview/catalog/__tests__/adr291CodeView.test.tsx (UPDATE_CODE_VIEW=1 rewrites).\n\n${code}`;
  if (process.env.UPDATE_CODE_VIEW === "1" || !existsSync(file)) {
    mkdirSync(GENERATED, { recursive: true });
    writeFileSync(file, text);
  }
  expect(text).toBe(readFileSync(file, "utf8"));
}

const SCHEMA = [
  { id: "o-id", key: "id", type: "string" },
  { id: "o-price", key: "price", type: "number" },
  { id: "o-qty", key: "qty", type: "number" },
  { id: "o-items", key: "items", type: "array" },
  {
    id: "o-total",
    key: "total",
    type: "number",
    formula: "'o-price' * 'o-qty'",
  },
  {
    id: "o-total-text",
    key: "total_text",
    type: "string",
    formula: "'o-price' * 'o-qty'",
  },
  {
    id: "o-items-sum",
    key: "items_sum",
    type: "number",
    formula: "sum('o-items'[*].price)",
  },
];
const ORDERS: CodeViewCollection = {
  id: "orders",
  name: "orders",
  schema: SCHEMA,
};
const ENTRY: CollectionEntry = {
  kind: "collection",
  id: "data:collection:orders" as CollectionEntry["id"],
  name: "orders",
  schema: SCHEMA,
  mockData: [],
  useMockData: true,
};

async function open(collection: CodeViewCollection = ORDERS) {
  vi.spyOn(console, "warn").mockImplementation(() => {});
  vi.spyOn(console, "error").mockImplementation(() => {});
  const h = await openAdr280Preview([]);
  const graph = () => h.workspace.runtime.graph;
  act(() => {
    h.workspace.execute(
      setDataEntries({ puts: [{ ...ENTRY, schema: collection.schema }] }),
    );
  });
  const definitionId = catalogPaletteDefinitionId(graph().library, "ListBox");
  const list = h.workspace.newId("node") as NodeId;
  act(() => {
    h.workspace.execute(
      insertNodes({
        parent: { kind: "node", id: BODY },
        entries: [
          {
            kind: "node",
            id: list,
            definitionId,
            children: [],
            props: catalogCreationProps(
              graph().library,
              definitionId,
              "ListBox",
            ),
            visual: {},
            sizing: {},
            descendantOverrides: [],
          } as NodeEntry,
        ],
        rootIds: [list],
        newId: h.workspace.newId,
      }),
    );
    h.workspace.execute(
      catalogBindingCommand(
        [{ kind: "node", id: list }],
        catalogBindingRef({
          source: "dataTable",
          collectionId: "orders",
          name: "orders",
        })!,
      ),
    );
  });
  const data = { collections: [collection], endpoints: [] };
  const code = () => catalogCodeView(graph(), HOME, data)!.code;
  const session = () => catalogCodeViewSession(graph(), HOME, data)!;
  const apply = (edited: string) => {
    const current = session();
    return catalogCodeViewApply(
      h.workspace,
      current,
      edited,
      changesOf(current.baseline.code, edited),
      data,
    );
  };
  const entry = () =>
    graph().getEntry("data:collection:orders") as CollectionEntry;
  return { ...h, graph, list, code, session, apply, entry, data };
}

/** One replacement as the editor's composed change (the differing middle of the texts). */
function changesOf(before: string, after: string) {
  let start = 0;
  while (
    start < before.length &&
    start < after.length &&
    before[start] === after[start]
  )
    start += 1;
  let endA = before.length;
  let endB = after.length;
  while (endA > start && endB > start && before[endA - 1] === after[endB - 1]) {
    endA -= 1;
    endB -= 1;
  }
  return [{ fromA: start, toA: endA, insert: after.slice(start, endB) }];
}

describe("ADR-291 code view — computed columns (golden 6 · the fields block as an edit unit)", () => {
  it("orders: the fields block (two types of one formula · an array sub-property) and the rows mapped through json-formula", async () => {
    const h = await open();
    const code = h.code();
    golden("orders", code);
    expect(code).toContain("import JsonFormula from '@adobe/json-formula';");
    expect(code).toContain("let formula = new JsonFormula();");
    expect(code).toContain("total: {type: 'number', formula: 'price * qty'},");
    expect(code).toContain(
      "total_text: {type: 'string', formula: 'price * qty'},",
    );
    expect(code).toContain(
      "items_sum: {type: 'number', formula: 'sum(items[*].price)'},",
    );
    expect(code).toContain(
      "let orders = ordersData.map(item => computed(item, ordersFields));",
    );
    // (The block is a `fields` statement, the helpers and the rows line derived.)
    const kinds = parseCodeView(code).statements.map((item) => item.kind);
    expect(kinds).toEqual(
      expect.arrayContaining(["formula", "fields", "computedRows"]),
    );
    expect(kinds.filter((kind) => kind === "view")).toHaveLength(0);
    h.view.unmount();
  });

  it("unchanged code plans nothing (strict); a formula typed over is stored over ids — one step", async () => {
    const h = await open();
    const current = h.session();
    const strict = catalogCodeViewPlan({
      reader: h.graph(),
      session: current,
      edited: current.baseline.code,
      changes: [],
      data: h.data,
      newId: h.workspace.newId,
      strict: true,
    });
    expect(strict.rejected).toEqual([]);
    // (G1 — every unit read again gives back the document's value: applying changes nothing.)
    const schemaBefore = JSON.stringify(h.entry().schema);
    if (strict.command) act(() => void h.workspace.execute(strict.command!));
    expect(JSON.stringify(h.entry().schema)).toBe(schemaBefore);
    expect(h.code()).toBe(current.baseline.code);

    const undo = h.workspace.runtime.historyDepth.undo;
    const edited = current.baseline.code.replace(
      "total: {type: 'number', formula: 'price * qty'},",
      "total: {type: 'number', formula: 'price * qty * 2'},",
    );
    const result = h.apply(edited);
    expect(result.rejected).toEqual([]);
    expect(result.applied).toBe(true);
    const total = h.entry().schema.find((field) => field.key === "total");
    expect(total?.formula).toBe("'o-price' * 'o-qty' * 2");
    expect(h.workspace.runtime.historyDepth.undo).toBe(undo + 1);
    // (The other computed columns untouched; the code shows the new formula over keys.)
    expect(
      h.entry().schema.find((field) => field.key === "total_text")?.formula,
    ).toBe("'o-price' * 'o-qty'");
    expect(h.code()).toContain("formula: 'price * qty * 2'");
    h.view.unmount();
  });

  it("a `type` typed over · a column read that the table lacks · a column added to the block are refused — nothing changes", async () => {
    const h = await open();
    const code = h.session().baseline.code;
    const before = JSON.stringify(h.entry().schema);
    const typed = h.apply(
      code.replace(
        "total: {type: 'number', formula: 'price * qty'},",
        "total: {type: 'string', formula: 'price * qty'},",
      ),
    );
    expect(typed.applied).toBe(false);
    expect(typed.rejected.map((line) => line.reason)).toContain(
      "outsideVocabulary",
    );
    const unknown = h.apply(
      code.replace(
        "total: {type: 'number', formula: 'price * qty'},",
        "total: {type: 'number', formula: 'price * discount'},",
      ),
    );
    expect(unknown.applied).toBe(false);
    expect(unknown.rejected.length).toBeGreaterThan(0);
    const added = h.apply(
      code.replace(
        "total: {type: 'number', formula: 'price * qty'},",
        "total: {type: 'number', formula: 'price * qty'},\n  extra: {type: 'number', formula: 'qty'},",
      ),
    );
    expect(added.applied).toBe(false);
    expect(JSON.stringify(h.entry().schema)).toBe(before);
    h.view.unmount();
  });

  it("a rename of a read column (price → unitPrice) changes the code, not the stored formula (G1)", async () => {
    const renamed: CodeViewCollection = {
      ...ORDERS,
      schema: SCHEMA.map((field) =>
        field.key === "price" ? { ...field, key: "unitPrice" } : field,
      ),
    };
    const h = await open(renamed);
    expect(h.code()).toContain(
      "total: {type: 'number', formula: 'unitPrice * qty'},",
    );
    expect(
      h.entry().schema.find((field) => field.key === "total")?.formula,
    ).toBe("'o-price' * 'o-qty'");
    h.view.unmount();
  });
});
