/**
 * Flatten the nested application catalog for React Aria's string formatter.
 *
 * The nested `translations` export remains available for existing data-driven
 * consumers while the formatter consumes dot-separated message keys.
 */
function flattenTranslationCatalog(
  value: unknown,
  prefix = "",
  result: Record<string, string> = {},
): Record<string, string> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return result;
  }

  for (const [key, nestedValue] of Object.entries(value)) {
    const messageKey = prefix ? `${prefix}.${key}` : key;

    if (typeof nestedValue === "string") {
      result[messageKey] = nestedValue;
    } else {
      flattenTranslationCatalog(nestedValue, messageKey, result);
    }
  }

  return result;
}

