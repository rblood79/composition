// ADR-256 Decision 7 — the state keys each RAC part gives its children as render props, generated
// from the installed RAC's run (`adr256-g0-rac-inventory.mjs` — the `values` its `useRenderProps`
// passes), never by hand. Only the keys a node's `showWhen` may test (`CATALOG_STATE_KEYS`); a part
// probed in another parent's context (`Button@Select`) or as a children function is its own part.
//
//   node apps/builder/scripts/adr256-g0-rac-inventory.mjs <inv.json>
//   node apps/builder/scripts/adr256-gen-rac-state-keys.mjs <inv.json> [out.ts]
import { readFileSync, writeFileSync } from "node:fs";

/** `CATALOG_STATE_KEYS` (`packages/shared/src/catalog/document/types.ts`), in its order. */
export const STATE_KEYS = [
  "isSelected",
  "isIndeterminate",
  "isExpanded",
  "isInvalid",
  "isDisabled",
  "isReadOnly",
  "isRequired",
  "isPressed",
  "isHovered",
  "isFocusVisible",
  "isOpen",
  "isCurrent",
  "hasSubmenu",
  "allowsRemoving",
  "allowsSorting",
];

export function buildRacStateKeys(inventory) {
  const table = {};
  for (const [probe, values] of Object.entries(inventory.renderProps)) {
    if (probe.includes("@")) continue;
    const part = probe.replace(/\(.*\)$/, "");
    const keys = STATE_KEYS.filter((key) => values.includes(key));
    if (keys.length) table[part] = keys;
  }
  return Object.fromEntries(
    Object.entries(table).sort(([a], [b]) => a.localeCompare(b)),
  );
}

export function renderRacStateKeys(inventory) {
  return `// GENERATED by apps/builder/scripts/adr256-gen-rac-state-keys.mjs from the installed RAC's run
// (adr256-g0-rac-inventory.mjs) — do not edit by hand. RAC ${inventory.racVersion}.
// ADR-256 Decision 7: the state keys each RAC part gives as render props (its \`useRenderProps\`
// values) — a node's \`showWhen\` condition reads the nearest ancestor part that gives the key.

export const RAC_STATE_KEYS_VERSION = ${JSON.stringify(inventory.racVersion)};

export const RAC_STATE_KEYS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(buildRacStateKeys(inventory), null, 2)};
`;
}

if (process.argv[1]?.endsWith("adr256-gen-rac-state-keys.mjs")) {
  const [, , input, out] = process.argv;
  const text = renderRacStateKeys(JSON.parse(readFileSync(input, "utf8")));
  if (out) writeFileSync(out, text);
  else process.stdout.write(text);
}
