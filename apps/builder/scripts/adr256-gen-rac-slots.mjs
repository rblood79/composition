#!/usr/bin/env node
// ADR-256 Decision 4 — the named-slot provider table, generated from the installed RAC's run
// (`adr256-g0-rac-inventory.mjs`), never by hand. Each probe position's consumer contexts are
// compared with its parent position's: what a part adds (a slot table, a plain context) or clears
// is that part's provision.
//
//   node apps/builder/scripts/adr256-g0-rac-inventory.mjs <inv.json>
//   node apps/builder/scripts/adr256-gen-rac-slots.mjs <inv.json> [out.ts]
import { readFileSync, writeFileSync } from "node:fs";

/** Consumer contexts a catalog part reads its slot from (key = the table's context key). */
const CONSUMERS = {
  TextContext: "Text",
  ButtonContext: "Button",
  HeadingContext: "Heading",
  CheckboxContext: "Checkbox",
  DateFieldContext: "DateField",
};
/** Probe segment names that are not the RAC part's own name. */
const SEGMENT_ALIAS = { Item: "ColorSwatchPickerItem" };

export function buildRacSlotProviders(inventory) {
  const table = {};
  const describe = (value) =>
    value === null
      ? { cleared: true }
      : value === "plain"
        ? { plain: true }
        : {
            slots: value.slots.filter((key) => key !== "DEFAULT"),
            ...(value.slots.includes("DEFAULT") ? { hasDefault: true } : {}),
          };
  for (const fixture of Object.values(inventory.fixtures)) {
    const positions = fixture.positions ?? {};
    for (const [position, contexts] of Object.entries(positions)) {
      const segments = position.split(">");
      // The parent position: the longest probed prefix (else the root — nothing provided).
      let parent = {};
      for (let n = segments.length - 1; n > 0; n -= 1) {
        const prefix = segments.slice(0, n).join(">");
        if (positions[prefix]) {
          parent = positions[prefix];
          break;
        }
      }
      // The provider: the innermost RAC part (an html element segment — `header` — is its parent's).
      const parts = segments
        .map((segment) => segment.replace(/\(.*\)$/, "").replace(/@.*$/, ""))
        .filter((segment) => /^[A-Z]/.test(segment));
      const raw = parts[parts.length - 1];
      if (!raw) continue;
      const provider = SEGMENT_ALIAS[raw] ?? raw;
      for (const [contextName, key] of Object.entries(CONSUMERS)) {
        const here = contexts[contextName];
        const above = parent[contextName];
        if (JSON.stringify(here) === JSON.stringify(above)) continue;
        if (here === undefined && above === undefined) continue;
        const provision = describe(here === undefined ? null : here);
        (table[provider] ??= {})[key] = provision;
      }
    }
  }
  return Object.fromEntries(
    Object.entries(table)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([provider, provisions]) => [
        provider,
        Object.fromEntries(
          Object.entries(provisions).sort(([a], [b]) => a.localeCompare(b)),
        ),
      ]),
  );
}

export function renderRacSlotProviders(inventory) {
  const table = buildRacSlotProviders(inventory);
  return `// GENERATED by apps/builder/scripts/adr256-gen-rac-slots.mjs from the installed RAC's run
// (adr256-g0-rac-inventory.mjs) — do not edit by hand. RAC ${inventory.racVersion}.
// ADR-256 Decision 4: what each RAC part provides to the children it renders, per consumer context —
// a slot table (\`slots\` + \`hasDefault\` = RAC's DEFAULT_SLOT), a plain context (\`plain\`: no names,
// the slot prop passes as is), or a cleared context (\`cleared\`: the part detaches its children).

export type RacSlotContextKey =
  | "Text"
  | "Button"
  | "Heading"
  | "Checkbox"
  | "DateField";

export interface RacSlotProvision {
  readonly slots?: readonly string[];
  readonly hasDefault?: true;
  readonly plain?: true;
  readonly cleared?: true;
}

export const RAC_SLOT_PROVIDERS_VERSION = ${JSON.stringify(inventory.racVersion)};

export const RAC_SLOT_PROVIDERS: Readonly<
  Record<string, Readonly<Partial<Record<RacSlotContextKey, RacSlotProvision>>>>
> = ${JSON.stringify(table, null, 2)};
`;
}

if (process.argv[1]?.endsWith("adr256-gen-rac-slots.mjs")) {
  const [, , input, out] = process.argv;
  const text = renderRacSlotProviders(JSON.parse(readFileSync(input, "utf8")));
  if (out) writeFileSync(out, text);
  else process.stdout.write(text);
}
